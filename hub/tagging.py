TOPIC_KINDS = ["广告反馈", "明星应援", "营销活动", "修辞误召回"]


def detect_topic(title: str, content: str) -> tuple[str, str]:
    """返回 (内容类型, 判定依据)。判定顺序即优先级。

    只看标题 + 摘要前 200 字：饭圈长文正文里什么词都有，看多了全是噪声。
    """
    t = title or ""
    body = (content or "")[:200]
    blob = f"{t} {body}"
    ad_ctx = any(w in blob for w in ("广告", "广子", "弹窗", "跳转", "摇一摇", "开屏广告"))

    if "开屏" in t and not ad_ctx:
        rh = _hit(blob, RHETORIC_CTX)
        if rh:
            return "修辞误召回", f"「开屏」在这里是修辞/动物义（{'/'.join(rh[:2])}），且不涉广告"
    strong = _hit(blob, FAN_STRONG)
    if strong:
        return "明星应援", f"饭圈硬特征：{'/'.join(strong[:3])}"
    weak = _hit(blob, FAN_WEAK)
    if len(weak) >= 2:
        return "明星应援", f"饭圈弱特征多处命中：{'/'.join(weak[:3])}"
    mkt = _hit(blob, MARKETING_WORDS)
    if mkt:
        return "营销活动", f"营销/权益内容：{'/'.join(mkt[:3])}"
    if weak:
        return "明星应援", f"饭圈弱特征：{weak[0]}"
    return "广告反馈", ""


