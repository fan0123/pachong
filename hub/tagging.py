def _norm(text: str) -> str:
    return re.sub(r"[\s|·．。，,、；;：:!！?？~～\-—_/\\【】\[\]()（）\"'“”‘’*#…]+", "",
                  text or "")


def _hit(text: str, words) -> list[str]:
    norm = _norm(text)
    return [w for w in words if w in (text or "") or _norm(w) in norm]


KEYWORD_TAIL = ("广告", "弹窗", "问题", "投诉")


def keyword_hit(title: str, content: str, keyword: str) -> bool:
    """采集侧的相关性闸门：抓回来的内容必须真的提到搜索词或它的核心词。

    为什么需要：搜索引擎会把"相关但不含词"的结果一起放出来（搜"开屏广告"返回一篇
    只讲"手机变慢"的稿子），这类条目进库后会污染声量。核心词是去掉尾部背景词后的部分
    （开屏广告→开屏、摇一摇广告→摇一摇），因为标题常写"开屏"而不写全"开屏广告"。
    """
    kw = (keyword or "").strip()
    if not kw:
        return True
    blob = _norm(f"{title or ''} {(content or '')[:600]}")
    cands = {_norm(kw)}
    for tail in KEYWORD_TAIL:
        if kw.endswith(tail) and len(kw) > len(tail):
            cands.add(_norm(kw[: -len(tail)]))
    return any(c and c in blob for c in cands)


def detect_actor(platform: str, author: str, metrics: dict, extra: dict) -> tuple[str, str]:
    """返回 (主体类型, 判定依据)。只看作者名 + 影响力指标，不看正文。"""
    name = (author or "").strip()
    if not name:
        # 没作者名时不硬判身份：自媒体平台留"自媒体号"，UGC 平台留"普通用户"
        if platform in SELFMEDIA_PLATFORMS:
            return "自媒体号", "无作者名，按平台性质归自媒体号"
        return "普通用户", "无作者名，按平台性质归普通用户"
    # 剥掉"官微/官方平台/客户端"这类运营后缀再判，否则"半岛网官微"会被当成企业号
    core = NAME_SUFFIX.sub("", name).strip("·- ") or name

    hits = _hit(core, GOV_WORDS)
    if hits:
        return "官方机构", f"账号名含政务/监管词：{'/'.join(hits[:2])}"
    if GOV_SUFFIX.search(core):
        return "官方机构", f"账号名符合政务号命名：{name}"

    hits = _hit(core, STATE_MEDIA)
    if hits:
        return "官方媒体", f"央媒/党媒名单命中：{hits[0]}"
    if PARTY_PAPER.match(core):
        return "官方媒体", f"省级党报：{core}"

    hits = _hit(core, BRAND_WORDS)
    if hits and (name in hits or core in hits or len(core) <= len(hits[0]) + 3):
        # "百度网盘""抖音客服"算平台号；"吐槽百度网盘的小明"这种长名字不算
        return "平台企业号", f"平台/企业官号：{hits[0]}"

    media = _hit(core, MEDIA_WORDS)
    if media:
        return "新闻媒体", f"账号名含媒体特征词：{'/'.join(media[:2])}"
    if MEDIA_SUFFIX.match(core) or MEDIA_TAIL.match(core):
        return "新闻媒体", f"账号名符合媒体命名（X网/X报/X台）：{core}"
    weak = _hit(core, MEDIA_WEAK)
    if weak and MEDIA_ORG_SUFFIX.search(core):
        return "新闻媒体", f"弱特征「{weak[0]}」+ 机构后缀，判持证媒体"

    # 企业后缀放在媒体判定之后：像"半岛网官微"该算媒体，"XX科技有限公司"才算企业
    if BRAND_SUFFIX.search(name):
        return "平台企业号", f"账号名带官方/客服/公司后缀：{name}"

    followers = 0
    try:
        followers = int(extra.get("followers") or 0)
    except (TypeError, ValueError):
        followers = 0
    likes = metrics.get("likes") or 0
    shares = metrics.get("shares") or 0
    engagement = metrics.get("engagement") or 0
    # 阈值走可配置项（页面「参数配置」里能改），不写死
    from . import settings
    th = settings.get("bigv")
    if followers >= th["followers"]:
        return "大V博主", f"粉丝 {followers} ≥ {th['followers']}"
    if likes >= th["likes"] or shares >= th["shares"] or engagement >= th["engagement"]:
        return "大V博主", (f"影响力达标（赞 {likes} / 转 {shares} / 互动 {engagement}）"
                        + ("，粉丝数未知" if not followers else f"，粉丝 {followers}"))

    if platform in SELFMEDIA_PLATFORMS:
        return "自媒体号", "自媒体平台账号，无媒体/机构特征"
    return "普通用户", "无机构特征且影响力未达大V阈值"


def detect_sentiment(title: str, content: str, neg_evidence: list[str]) -> tuple[str, str]:
    """返回 (情感, 判定依据)。

    neg_evidence 由 clean.negative_evidence() 给出（吐槽/投诉/受损/批评倾向/激烈口语/诉求句式）。
    裁决顺序：先看负面（舆情场景里漏判负面代价最大）→ 再看标题里的明确正面表达 → 兜底中性。
    正面只认标题，且遇到软文/横评标记直接不给正面：软文里的"无广告、干净"是卖点不是口碑。
    """
    title = title or ""
    if neg_evidence:
        return "负面", "负面证据：" + "；".join(neg_evidence[:3])
    pos = _hit(title, POS_WORDS)
    if pos:
        promo = _hit(title, PROMO_MARK)
        if promo:
            return "中性", f"有正面词但属推荐/横评内容（{promo[0]}），不计正面"
        return "正面", "标题正面表达：" + "/".join(pos[:3])
    proc = _hit(f"{title} {(content or '')[:200]}", NEUTRAL_PROC)
    if proc:
        return "中性", "流程/事实叙述：" + "/".join(proc[:3])
    return "中性", "无明显情感倾向词"


# 主体 × 情感 → 兼容老口径的 layer（看板/导出仍按 layer 分主口径与噪音）
def derive_layer(actor: str, sentiment: str, relevant: bool, noise_reason: str) -> tuple[str, str]:
    if not relevant:
        return "D_噪音", noise_reason or "与开屏/摇一摇场景无关"
    if sentiment == "负面":
        if actor in MEDIA_ACTORS:
            return "B_媒体负面报道", f"{actor}发布的负面内容"
        return "A_UGC负反馈", f"{actor}发布的负面反馈"
    if sentiment == "正面":
        return "E_正面反馈", f"{actor}发布的正面内容"
    return "C_中性事件报道", f"{actor}发布的中性内容"
